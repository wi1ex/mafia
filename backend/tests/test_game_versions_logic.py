def version(claimant_id: int, *checks: tuple[int, str]) -> dict[str, object]:
    return {
        "claimant_id": claimant_id,
        "checks": [
            {"target_id": target_id, "verdict": verdict}
            for target_id, verdict in checks
        ],
    }


